function jsonResponse(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "access-control-allow-origin": "*",
      "access-control-allow-methods": "GET, POST, OPTIONS",
      "access-control-allow-headers": "Content-Type"
    }
  });
}

export default {
  async fetch(request) {
    if (request.method === "OPTIONS") {
      return new Response(null, {
        status: 204,
        headers: {
          "access-control-allow-origin": "*",
          "access-control-allow-methods": "GET, POST, OPTIONS",
          "access-control-allow-headers": "Content-Type"
        }
      });
    }

    if (request.method === "GET") {
      return jsonResponse({
        ok: true,
        version: VERSION,
        message: "Compatibility calculator is ready. Send POST with two birth dates."
      });
    }

    if (request.method !== "POST") {
      return jsonResponse({
        ok: false,
        version: VERSION,
        error: "Use GET or POST."
      }, 405);
    }

    let rawBody = "";

    try {
      rawBody = await request.text();

      let payload;

      try {
        payload = JSON.parse(rawBody);
      } catch (_) {
        payload = { text: rawBody };
      }

      const dates = extractDates(payload);

      if (dates.length < 2) {
        return jsonResponse({
          ok: false,
          version: VERSION,
          error: "Не удалось найти две даты рождения. Передайте даты в формате ДД.ММ.ГГГГ, например: 09.06.1979 и 29.11.1974.",
          received: payload
        }, 400);
      }

      const result = buildText(dates[0], dates[1]);

      return jsonResponse({
        ok: true,
        version: VERSION,
        text: result.text,
        pair: result.pair,
        people: result.people
      });
    } catch (error) {
      return jsonResponse({
        ok: false,
        version: VERSION,
        error: "Ошибка при расчёте совместимости.",
        details: String(error && error.message || error)
      }, 500);
    }
  }
};
