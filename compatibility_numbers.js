function reduceNumber(number) {
  while (number > 9) {
    number = String(number)
      .split("")
      .reduce((sum, digit) => sum + Number(digit), 0);
  }
  return number;
}

function validateNumbers(numbers) {
  return Array.isArray(numbers) &&
    numbers.length === 3 &&
    numbers.every(
      number =>
        Number.isInteger(number) &&
        number >= 1 &&
        number <= 9
    );
}

function calculate(woman, man) {
  const womanFinal = reduceNumber(
    woman[0] + woman[1] + woman[2]
  );

  const manFinal = reduceNumber(
    man[0] + man[1] + man[2]
  );

  const compatibility = {
    consciousness: reduceNumber(woman[0] + man[0]),
    realization: reduceNumber(woman[1] + man[1]),
    mission: reduceNumber(woman[2] + man[2]),
    final: reduceNumber(womanFinal + manFinal)
  };

  const keys = [
    "consciousness",
    "realization",
    "mission",
    "final"
  ];

  const labels = [
    "Сознание",
    "Реализация",
    "Миссия",
    "Финал"
  ];

  const short = keys.map((key, index) => {
    const number = compatibility[key];
    const item = meanings[key][number];

    return `${labels[index]} — ${number}: ${item[0]}. ${item[1]}`;
  }).join("\n\n");

  const detailed = [
    "ПОДРОБНАЯ РАСШИФРОВКА СОВМЕСТИМОСТИ",
    "",
    `Женщина: ${woman.join(", ")}`,
    `Мужчина: ${man.join(", ")}`,
    "",
    `Финальное число женщины: ${womanFinal}`,
    `Финальное число мужчины: ${manFinal}`,
    "",
    ...keys.map((key, index) => {
      const number = compatibility[key];
      const item = meanings[key][number];

      return `${labels[index]} — ${number}\n${item[0]}\n\n${item[1]}`;
    }),
    "",
    "ОБЩИЙ ПОРТРЕТ",
    "",
    `В сознании пары проявляется тема «${meanings.consciousness[compatibility.consciousness][0].toLowerCase()}».`,
    `В повседневной жизни особенно важна тема «${meanings.realization[compatibility.realization][0].toLowerCase()}».`,
    `Главная задача союза — «${meanings.mission[compatibility.mission][0].toLowerCase()}».`,
    `Итоговая энергия — «${meanings.final[compatibility.final][0].toLowerCase()}».`,
    "",
    "Это символическая нумерологическая интерпретация, а не гарантированный прогноз поведения или будущего отношений."
  ].join("\n");

  return {
    woman,
    man,
    womanFinal,
    manFinal,
    compatibility,
    short,
    detailed
  };
}

export default {
  async fetch(request) {
    const headers = {
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type"
    };

    if (request.method === "OPTIONS") {
      return new Response(null, { headers });
    }

    if (request.method !== "POST") {
      return Response.json({
        message: "Отправьте POST-запрос с массивами woman и man.",
        example: {
          woman: [8, 5, 4],
          man: [7, 6, 4]
        }
      }, { headers });
    }

    try {
      const body = await request.json();
      const { woman, man } = body;

      if (!validateNumbers(woman) || !validateNumbers(man)) {
        return Response.json({
          error: "Укажите по три целых числа от 1 до 9 для каждого человека."
        }, {
          status: 400,
          headers
        });
      }

      const result = calculate(woman, man);

      // Пока возвращаем обе версии для тестирования.
      // Позже подключим выдачу detailed только после оплаты.
      const mode = body.mode === "full" ? "full" : "short";

      return Response.json({
        woman: result.woman,
        man: result.man,
        womanFinal: result.womanFinal,
        manFinal: result.manFinal,
        compatibility: result.compatibility,
        mode,
        result: mode === "full" ? result.detailed : result.short
      }, {
        headers: {
          ...headers,
          "Content-Type": "application/json; charset=utf-8"
        }
      });
    } catch {
      return Response.json({
        error: "Не удалось прочитать запрос. Проверьте формат JSON."
      }, {
        status: 400,
        headers
      });
    }
  }
};
