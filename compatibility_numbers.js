function reduceNumber(value) {
  let n = Math.abs(Number(value) || 0);
  while (n > 9) {
    n = String(n).split("").reduce((sum, digit) => sum + Number(digit), 0);
  }
  return n || 0;
}

function digitsSum(value) {
  return String(value).replace(/\D/g, "").split("").reduce((sum, digit) => sum + Number(digit), 0);
}

function parseDate(value) {
  const match = String(value || "").trim().match(/^(\d{1,2})[./-](\d{1,2})[./-](\d{4})$/);
  if (!match) return null;

  const day = Number(match[1]);
  const month = Number(match[2]);
  const year = Number(match[3]);
  const date = new Date(Date.UTC(year, month - 1, day));

  if (
    date.getUTCFullYear() !== year ||
    date.getUTCMonth() !== month - 1 ||
    date.getUTCDate() !== day
  ) return null;

  const normalized = `${String(day).padStart(2, "0")}.${String(month).padStart(2, "0")}.${year}`;
  const consciousness = reduceNumber(day);
  const realization = reduceNumber(
    digitsSum(`${String(day).padStart(2, "0")}${String(month).padStart(2, "0")}${year}`)
  );
  const mission = reduceNumber(consciousness + realization);
  const final = reduceNumber(consciousness + realization + mission);

  return { date: normalized, consciousness, realization, mission, final };
}

function findDatesInText(text) {
  const matches = String(text || "").match(/\b\d{1,2}[./-]\d{1,2}[./-]\d{4}\b/g) || [];
  return matches.map(parseDate).filter(Boolean);
}

function extractDates(payload) {
  const found = [];
  const visited = new Set();

  function walk(value, depth) {
    if (depth > 6 || value == null) return;

    if (typeof value === "string") {
      const parsed = findDatesInText(value);
      found.push(...parsed);

      if (parsed.length === 0 && value.trim().startsWith("{")) {
        try {
          walk(JSON.parse(value), depth + 1);
        } catch (_) {}
      }
      return;
    }

    if (typeof value !== "object" || visited.has(value)) return;
    visited.add(value);

    if (Array.isArray(value)) {
      value.forEach(item => walk(item, depth + 1));
      return;
    }

    for (const [key, child] of Object.entries(value)) {
      if (
        typeof child === "string" &&
        /date|text|reply|message|input|body|data|value/i.test(key)
      ) {
        walk(child, depth + 1);
      } else if (typeof child === "object") {
        walk(child, depth + 1);
      }
    }
  }

  walk(payload, 0);

  const unique = [];
  const seen = new Set();

  for (const item of found) {
    if (!seen.has(item.date)) {
      seen.add(item.date);
      unique.push(item);
    }
  }

  return unique.slice(0, 2);
}

function pairNumber(a, b) {
  return reduceNumber(a + b);
}

