export default {
  async fetch(request) {
    if (request.method === "OPTIONS") {
      return new Response(null, {
        status: 204,
        headers: HEADERS
      });
    }

    if (request.method === "GET") {
      return reply({
        ok: true,
        service: "compatibility-calculator-decoding",
        version: VERSION,
        message:
          "Отправьте POST JSON с womanDate и manDate в формате ДД.ММ.ГГГГ."
      });
    }

    if (request.method !== "POST") {
      return reply({
        ok: false,
        version: VERSION,
        error: "Используйте POST-запрос."
      }, 405);
    }

        try {
      const body = await request.json();

      let calculation;

      if (body.text) {
        const dates = String(body.text).match(
          /\b\d{2}\.\d{2}\.\d{4}\b/g
        ) || [];

        if (dates.length !== 2) {
          throw new Error(
            "В результате первого API не найдены две даты рождения."
          );
        }

        calculation = calculate(dates[0], dates[1]);
      } else if (body.womanDate && body.manDate) {
        calculation = calculate(
          body.womanDate,
          body.manDate
        );
      } else {
        throw new Error(
          "Второй API не получил результат первого API. Проверьте Body: {\"text\":\"{{api_result}}\"}."
        );
      }

      const report = buildReport(calculation);

      return reply({
        ok: true,
        version: VERSION,
        text: report.text,
        dates: calculation.dates,
        pair: calculation.pair,
        individual: calculation.individual,
        numbers: report.numbers
      });
    } catch (error) {
      const message =
        error.message ||
        "Не удалось выполнить расчёт.";

      return reply({
        ok: false,
        version: VERSION,
        error: message,
        text: message
      }, 400);
    }
  }
};
